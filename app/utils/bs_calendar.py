class BSDateError(ValueError):
    """Raised for out-of-range or invalid BS dates."""


@dataclass(frozen=True)
class BSDate:
    year: int
    month: int
    day: int

    def __post_init__(self) -> None:  # pragma: no cover - dataclass validation
        if self.year not in BS_MONTH_DAYS:
            raise BSDateError(f"BS year {self.year} out of supported range")
        if not 1 <= self.month <= 12:
            raise BSDateError("month must be 1..12")
        if not 1 <= self.day <= BS_MONTH_DAYS[self.year][self.month - 1]:
            raise BSDateError("day out of range for the given BS month")

    def to_ad(self) -> date:
        return bs_to_ad(self.year, self.month, self.day)

    def month_name(self, lang: str = "en") -> str:
        return (MONTHS_NE if lang == "ne" else MONTHS_EN)[self.month - 1]


def _days_between(start: date, end: date) -> int:
    return (end - start).days


def bs_to_ad(year: int, month: int, day: int) -> date:
    bs = BSDate(year, month, day)
    days = 0
    for y in range(MIN_BS_YEAR, bs.year):
        days += sum(BS_MONTH_DAYS[y])
    for m in range(1, bs.month):
        days += BS_MONTH_DAYS[bs.year][m - 1]
    days += bs.day - 1
    return REFERENCE_AD + timedelta(days=days)


def ad_to_bs(value: date) -> BSDate:
    total = _days_between(REFERENCE_AD, value)
    if total < 0:
        raise BSDateError("date is before the supported BS range")
    for year in range(MIN_BS_YEAR, MAX_BS_YEAR + 1):
        for month in range(1, 13):
            length = BS_MONTH_DAYS[year][month - 1]
            if total < length:
                return BSDate(year, month, total + 1)
            total -= length
    raise BSDateError("date is after the supported BS range")


def weekday_name(value: date, lang: str = "en") -> str:
    return (WEEKDAYS_NE if lang == "ne" else WEEKDAYS_EN)[value.weekday()]


def format_bs(bs: BSDate, lang: str = "en") -> str:
    return f"{bs.month_name(lang)} {bs.day}, {bs.year}"
